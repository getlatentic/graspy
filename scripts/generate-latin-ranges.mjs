// Refreshes the table of Latin-script letters that the web app's nameKey and the server's
// normalise both fold by, from the Unicode version of the Node that runs this:
//
//   node scripts/generate-latin-ranges.mjs
//
// It writes apps/web/src/features/learn/lib/latin-ranges.json (the source) and
// apps/server/src/app/agent/latin_ranges.py (its copy). Run it only to move to a newer Unicode,
// then regenerate the name corpus (see docs/DEVELOPMENT.md). Neither the tests nor the app read
// the engine's own tables for this, so a different Node never changes a result.
import { writeFileSync } from "node:fs";

const latin = /\p{Script=Latin}/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10ffff; cp += 1) {
  const surrogate = cp >= 0xd800 && cp <= 0xdfff;
  const yes = !surrogate && latin.test(String.fromCodePoint(cp));
  if (yes && start < 0) start = cp;
  if (!yes && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}
if (start >= 0) ranges.push([start, 0x10ffff]);

const unicode = process.versions.unicode;
writeFileSync(
  "apps/web/src/features/learn/lib/latin-ranges.json",
  `${JSON.stringify({ unicode, ranges })}\n`,
);
const rows = ranges.map(([a, b]) => `    (${a}, ${b}),\n`).join("");
writeFileSync(
  "apps/server/src/app/agent/latin_ranges.py",
  `"""The code points of Unicode's Script=Latin, as (first, last) ranges, for the Unicode version
below. Generated by scripts/generate-latin-ranges.mjs, with the same list in the web app's
latin-ranges.json; a test holds the two equal."""

LATIN_UNICODE = "${unicode}"
LATIN_RANGES = (
${rows})
`,
);
console.log(`Unicode ${unicode}: ${ranges.length} ranges`);
