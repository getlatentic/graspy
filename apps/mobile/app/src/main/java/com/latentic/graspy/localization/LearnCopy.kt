    val askTitle: String,
    val askDetail: String,
    val practiseTitle: String,
    val practiseDetail: String,
    val planTitle: String,
    val planDetail: String,
    val practiseDraft: String,
    val practiseDraftAny: String,
    val planDraft: String,
)

/** A subject and its topics. */
data class SubjectCopy(
    val back: String,
    val progress: String,
    val progressLabel: String,
    val learnt: String,
    val ready: String,
    val notStarted: String,
    val goal: String,
    val lessonsCompleted: String,
    val topicsLoading: String,
)

/** The plan itself. */
data class PlanCopy(
    val edit: String,
    val buildFailed: String,
    val tryAgain: String,
)

/** A plan being made. */
data class PlanBuildingCopy(
    val making: String,
)

/** The You tab. */
data class YouCopy(
    val progress: String,
    val details: String,
    val country: String,
    val language: String,
    val grade: String,
    val editSubjects: String,
    val practice: String,
