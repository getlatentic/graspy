    val account: String,
    val learningAs: String,
    val switchLearner: String,
    val manageLearners: String,
    val signOut: String,
    val onMyOwn: String,
)

/** Levels after secondary school. */
data class LevelCopy(
    val undergraduate: String,
    val graduate: String,
)

/** The learner's details, and whether they get a new plan. */
data class DetailsCopy(
    val back: String,
    val title: String,
    val save: String,
    val askTitle: String,
    val askBody: String,
    val newPlan: String,
    val keepPlan: String,
)

/** Voice lessons, and the note shown before the first. */
data class VoiceNoteCopy(
    val title: String,
    val start: String,
    val note: String,
    val ok: String,
)

