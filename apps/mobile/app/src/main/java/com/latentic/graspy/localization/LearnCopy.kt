package com.latentic.graspy.localization

// The web app's own words (apps/web/src/locales), key for key: WebWordsTest holds them to it.

/** The learner's app beyond voice lessons, in the web app's words. */
data class LearnCopy(
    val nav: NavCopy,
    val home: PlanHomeCopy,
    val subject: SubjectCopy,
    val plan: PlanCopy,
    val planBuilding: PlanBuildingCopy,
    val you: YouCopy,
    val level: LevelCopy,
    val details: DetailsCopy,
    val voice: VoiceNoteCopy,
    val chat: ChatCopy,
    val ask: AskCopy,
    val lesson: TopicLessonCopy,
    val onboarding: PlanOnboardingCopy,
)

/** The tab bar. */
data class NavCopy(
    val label: String,
    val home: String,
    val subjects: String,
    val ask: String,
    val you: String,
)

/** Home's plan sections. */
data class PlanHomeCopy(
    val continueTitle: String,
