/** A topic's lesson. */
data class TopicLessonCopy(
    val loading: String,
    val loadFailed: String,
    val tryAgain: String,
    val backTo: String,
)

data class PlanOnboardingStepsProfileCopy(
    val title: String,
)

data class PlanOnboardingStepsSubjectsCopy(
    val title: String,
)

data class PlanOnboardingStepsCopy(
    val profile: PlanOnboardingStepsProfileCopy,
    val subjects: PlanOnboardingStepsSubjectsCopy,
)

data class PlanOnboardingProfileCopy(
