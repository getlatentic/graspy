    val title: String,
    val body: String,
    val `continue`: String,
)

/** Making a plan: the learner, their subjects, then the plan. */
data class PlanOnboardingCopy(
    val stepOf: String,
    val back: String,
    val next: String,
    val start: String,
    val settingUp: String,
    val steps: PlanOnboardingStepsCopy,
    val profile: PlanOnboardingProfileCopy,
    val subjects: PlanOnboardingSubjectsCopy,
    val generating: PlanOnboardingGeneratingCopy,
    val ready: PlanOnboardingReadyCopy,
    val moreSubjects: String,
)

fun learnCopyFor(language: InterfaceLanguage): LearnCopy = when (language) {
    InterfaceLanguage.ENGLISH -> ENGLISH_LEARN
    InterfaceLanguage.YORUBA -> YORUBA_LEARN
    InterfaceLanguage.PIDGIN -> PIDGIN_LEARN
    InterfaceLanguage.ARABIC -> ARABIC_LEARN
}

